export function iconSvg(name) {
  const body = ICONS[name] || "";
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

// Fill every [data-icon] element under root with its SVG (labels after an icon span are kept).
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (el.dataset.hydrated === el.dataset.icon) return;
    const svg = iconSvg(el.dataset.icon);
    if (el.tagName === "SPAN" || (el.children.length === 0 && el.textContent.trim() === "")) el.innerHTML = svg;
    el.dataset.hydrated = el.dataset.icon;
  });
}
